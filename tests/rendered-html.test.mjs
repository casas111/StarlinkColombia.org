import assert from "node:assert/strict";
import test from "node:test";

const developmentPreviewMeta =
  /<meta(?=[^>]*\bname=["']codex-preview["'])(?=[^>]*\bcontent=["']development["'])[^>]*>/i;

test("renders the production identity and independence disclosure", async () => {
  const workerUrl = new URL("../dist/server/index.js", import.meta.url);
  workerUrl.searchParams.set("test", `${process.pid}-${Date.now()}`);
  const { default: worker } = await import(workerUrl.href);

  const response = await worker.fetch(
    new Request("http://localhost/", {
      headers: { accept: "text/html" },
    }),
    {
      ASSETS: {
        fetch: async () => new Response("Not found", { status: 404 }),
      },
    },
    {
      waitUntil() {},
      passThroughOnException() {},
    },
  );

  assert.equal(response.status, 200);
  assert.match(
    response.headers.get("content-type") ?? "",
    /^text\/html\b/i,
  );
  const html = await response.text();

  assert.match(html, /<title>Conecta Colombia — Solicitud Starlink<\/title>/i);
  assert.match(
    html,
    /Portal independiente de Conecta Colombia para solicitar conectividad en comunidades y servicios esenciales de Colombia\./i,
  );
  assert.match(
    html,
    /Proyecto independiente\. No afiliado, patrocinado ni operado por Starlink o SpaceX\./i,
  );
  assert.doesNotMatch(html, developmentPreviewMeta);
});
